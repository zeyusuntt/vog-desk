"""Write the results report for a split: tables, reliability diagram, relative value curve, bootstrap intervals.

Reads the forecasts from scripts/evaluate.py's dump and the desk backtests, writes docs/RESULTS_<split>.md
and PNG figures under docs/figures/. The held-out report (docs/RESULTS.md) is written once.

Usage: .venv/bin/python scripts/results.py --split dev [--t-star 0.19]
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from vogdesk import dataset, model, sources  # noqa: E402
from vogdesk.metrics import auc, block_bootstrap_diff, brier, bss, contingency, csi_max_threshold, reliability  # noqa: E402

sys.path.insert(0, str(ROOT / "scripts"))
from evaluate import forecasts  # noqa: E402

FIG = ROOT / "docs" / "figures"
NAMES = {"climatology": "1 climatology", "persistence": "2 persistence", "episode_rule": "3 episode rule", "model": "4 model only",
         "desk_no_review": "5 desk, no review", "desk_full": "6 full desk", "recent_rate": "7 recent rate"}


def relative_value(p: np.ndarray, y: np.ndarray, ratios: np.ndarray) -> np.ndarray:
    """Richardson relative economic value: for each cost-loss ratio, act when p >= ratio; compare with always/never act."""
    base = y.mean()
    out = []
    for r in ratios:
        warn = p >= r
        hit = np.mean(warn & (y == 1)); fa = np.mean(warn & (y == 0)); miss = np.mean(~warn & (y == 1))
        expense = (hit + fa) * r + miss
        clim = min(r, base)  # the better of always act (r) and never act (base)
        perfect = base * r
        out.append((clim - expense) / (clim - perfect) if clim > perfect else np.nan)
    return np.array(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=list(dataset.SPLITS), default="dev")
    ap.add_argument("--t-star", type=float, default=None, help="frozen action threshold; default: CSI max on this split (dev only)")
    ap.add_argument("--out", default=None)
    ap.add_argument("--tag", default="v4", help="desk backtest version to read (file suffix); v4 is the frozen desk")
    ap.add_argument("--i-am-sure", action="store_true", help="required for the held-out split, which is scored once")
    args = ap.parse_args()
    if args.split == "heldout" and not args.i_am_sure:
        sys.exit("The held-out split is reported once. Pass --i-am-sure.")
    src = sources.load()
    X, lab = dataset.build(src, args.split)
    y = lab["event"].astype(float)
    m = model.load()
    f = forecasts(src, X, m, args.split, args.tag)
    cols = [c for c in NAMES if c in f and f[c].notna().any()]
    FIG.mkdir(parents=True, exist_ok=True)
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()

    lines = [f"# Results on the {args.split} period", "",
             f"Generated by `scripts/results.py --split {args.split}` at commit `{head}`. {len(y)} valid nights, {int(y.sum())} events, base rate {y.mean():.3f}. "
             f"Event: any hourly SO2 >= 75 ppb at Pahala between 18:00 and 12:00 HST. An hourly mean of 75 ppb does not show that a 15-minute average reached the schools plan's yellow level.", ""]
    rows = []
    t_star = {}
    for c in cols:
        p = f[c].to_numpy(float)
        if c in ("persistence", "episode_rule"):
            t = 1.0
        elif args.t_star is not None and c in ("model", "desk_no_review", "desk_full"):
            t = args.t_star
        else:
            t = csi_max_threshold(p, y) if c != "climatology" else np.nan
        t_star[c] = t
        ok = ~np.isnan(p)
        ct = contingency(p[ok], y[ok], t) if not np.isnan(t) else None
        rows.append({"forecast": NAMES[c], "n": int(ok.sum()), "Brier": brier(p[ok], y[ok]), "BSS vs clim": bss(p[ok], y[ok], dataset.CLIMATOLOGY),
                     "BSS vs persist": bss(p[ok], y[ok], f["persistence"].to_numpy(float)[ok]),
                     "AUC": auc(p[ok], y[ok]) if c not in ("persistence", "episode_rule", "climatology") else np.nan,
                     "t*": t, "hits": ct["hits"] if ct else np.nan, "misses": ct["misses"] if ct else np.nan,
                     "FA": ct["false_alarms"] if ct else np.nan, "POD": ct["POD"] if ct else np.nan, "FAR": ct["FAR"] if ct else np.nan,
                     "CSI": ct["CSI"] if ct else np.nan})
    lines += [pd.DataFrame(rows).to_markdown(index=False, floatfmt=".3f"), "",
              "t* for forecasts 4 to 6 is " + ("the frozen value" if args.t_star is not None else "the CSI-maximising value on this split (PREREG grid 0.01 to 0.60)") + ".", ""]

    # Paired comparisons with block bootstrap
    lines += ["## Paired Brier differences (7-day block bootstrap, 90% intervals; 3- and 14-day sensitivity)", ""]
    pairs = [("desk_full", "model"), ("desk_full", "recent_rate"), ("desk_full", "desk_no_review"), ("desk_no_review", "model"), ("model", "climatology"), ("recent_rate", "climatology")]
    prow = []
    for a, b in pairs:
        if a not in f or b not in f or f[a].isna().all() or f[b].isna().all():
            continue
        ok = f[a].notna() & f[b].notna()
        r7 = block_bootstrap_diff(f.loc[ok, a], f.loc[ok, b], y[ok], f.index[ok], 7)
        r3 = block_bootstrap_diff(f.loc[ok, a], f.loc[ok, b], y[ok], f.index[ok], 3)
        r14 = block_bootstrap_diff(f.loc[ok, a], f.loc[ok, b], y[ok], f.index[ok], 14)
        prow.append({"comparison": f"{NAMES[a]} minus {NAMES[b]}", "nights": int(ok.sum()), "difference": r7["diff"],
                     "90% CI (7-day blocks)": f"[{r7['ci90'][0]:+.4f}, {r7['ci90'][1]:+.4f}]",
                     "3-day": f"[{r3['ci90'][0]:+.4f}, {r3['ci90'][1]:+.4f}]", "14-day": f"[{r14['ci90'][0]:+.4f}, {r14['ci90'][1]:+.4f}]",
                     "blocks with an event": r7["blocks_with_event"]})
    if prow:
        lines += [pd.DataFrame(prow).to_markdown(index=False, floatfmt="+.4f"), "",
                  "A negative difference means the first forecast has the lower (better) Brier score. The number of 7-day blocks with at least one event is the effective sample size.", ""]

    # Handovers
    for c in ("desk_full", "desk_no_review"):
        hcol = c + "_handover"
        if hcol in f and f[hcol].notna().any():
            h = f[hcol].fillna(False).astype(bool)
            if h.any():
                yy = y[h]
                lines += [f"{NAMES[c]}: {int(h.sum())} nights handed to a human ({yy.sum():.0f} of them events, rate {yy.mean():.2f}); scored at the shown probability and never counted as correct.", ""]

    # Reliability diagram
    fig, ax = plt.subplots(figsize=(5.5, 5.5))
    ax.plot([0, 1], [0, 1], color="grey", lw=1)
    for c in ("model", "desk_full", "desk_no_review", "recent_rate"):
        if c in f and f[c].notna().any():
            ok = f[c].notna()
            rel = reliability(f.loc[ok, c], y[ok])
            rel = rel[rel.n > 0]
            ax.plot(rel.mean_p, rel.obs_freq, marker="o", label=NAMES[c])
            for _, r in rel.iterrows():
                ax.annotate(str(r.n), (r.mean_p, r.obs_freq), textcoords="offset points", xytext=(4, 4), fontsize=7)
    ax.set_xlabel("forecast probability"); ax.set_ylabel("observed frequency"); ax.set_title(f"Reliability, {args.split} ({len(y)} nights, {int(y.sum())} events)")
    ax.legend(fontsize=8); ax.set_xlim(0, 1); ax.set_ylim(0, 1)
    fig.tight_layout(); fig.savefig(FIG / f"reliability_{args.split}.png", dpi=150); plt.close(fig)

    # Relative value curve
    ratios = np.round(np.arange(0.05, 0.501, 0.01), 2)
    fig, ax = plt.subplots(figsize=(6, 4))
    for c in ("model", "desk_full", "desk_no_review", "recent_rate"):
        if c in f and f[c].notna().any():
            ok = f[c].notna()
            ax.plot(ratios, relative_value(f.loc[ok, c].to_numpy(float), y[ok].to_numpy(), ratios), label=NAMES[c])
    ax.axhline(0, color="grey", lw=1); ax.set_ylim(-0.5, 1); ax.set_xlabel("cost-loss ratio of acting on a warning"); ax.set_ylabel("relative economic value")
    ax.set_title("Value against always-act / never-act"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(FIG / f"value_{args.split}.png", dpi=150); plt.close(fig)
    lines += ["## Figures", "", f"![reliability](figures/reliability_{args.split}.png)", "", f"![value](figures/value_{args.split}.png)", ""]

    # Reliability tables
    for c in ("desk_full", "model", "recent_rate"):
        if c in f and f[c].notna().any():
            ok = f[c].notna()
            lines += [f"### Reliability bins, {NAMES[c]}", "", reliability(f.loc[ok, c], y[ok]).to_markdown(index=False, floatfmt=".3f"), ""]

    out = Path(args.out) if args.out else ROOT / "docs" / (f"RESULTS.md" if args.split == "heldout" else f"RESULTS_{args.split}.md")
    out.write_text("\n".join(lines))
    print("\n".join(lines[:12]))
    print(f"wrote {out} and figures under {FIG}")


if __name__ == "__main__":
    main()
